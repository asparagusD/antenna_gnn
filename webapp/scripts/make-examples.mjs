/**
 * Writes src/model/examples.json: one known single-band, functioning example antenna per grid, taken
 * from the committed C1.3 golden fixtures (webapp/fixtures/NxN.json) and stored as share strings
 * (src/core/share.ts format: p=v1.<N>.<base64url bitset, row-major, MSB first>).
 *
 * Usage (from webapp/): node scripts/make-examples.mjs
 * src/model/examples.test.ts checks the file against the fixtures.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const PICK = {
  12: '12x12-ref-sample_0',
  15: '15x15-ref-sample_55',
  25: '25x25-rand-fill70',
  35: '35x35-ref-sample_32',
  45: '45x45-ref-sample_1',
};

function share(N, pattern) {
  const bytes = new Uint8Array(Math.ceil((N * N) / 8));
  pattern.forEach((v, k) => {
    if (v === 1) bytes[k >> 3] |= 0x80 >> (k & 7);
  });
  const b64 = Buffer.from(bytes)
    .toString('base64')
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
  return `p=v1.${N}.${b64}`;
}

const examples = Object.entries(PICK).map(([n, id]) => {
  const N = Number(n);
  const fixture = JSON.parse(readFileSync(new URL(`../fixtures/${n}x${n}.json`, import.meta.url), 'utf8'));
  const c = fixture.cases.find((x) => x.id === id);
  if (c === undefined) throw new Error(`no fixture case ${id}`);
  if (c.predicted_bands !== 1 || c.predicted_functioning !== true)
    throw new Error(`${id} is not single-band functioning`);
  return { N, fixture_id: id, share: share(N, c.pattern), predicted_min_db: c.predicted_min_db };
});

const out = {
  schema: 'graphpatch.examples/v1',
  source: 'webapp/fixtures (C1.3 golden fixtures); generated by webapp/scripts/make-examples.mjs',
  note: 'One single-band, functioning example per grid (the deployed model predicts one band below -10 dB).',
  examples,
};
writeFileSync(new URL('../src/model/examples.json', import.meta.url), `${JSON.stringify(out, null, 2)}\n`);
console.log(examples.map((e) => `${e.N}: ${e.fixture_id} (${e.predicted_min_db.toFixed(1)} dB)`).join('\n'));
